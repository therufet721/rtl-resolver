import fs from "node:fs";
import { manifest, readVerified, resolveOutput } from "./unicode-source.mjs";

/**
 * Derive the committed offline conformance fixture from the official
 * BidiCharacterTest.txt. The selection is deterministic so regenerating it
 * against the same pinned Unicode release reproduces the file byte for byte,
 * and the recorded hash ties every committed case back to its source.
 */
const HEAD = 100;
const STRIDE = 200;
const SELECTION = `the first ${HEAD} data lines, then every ${STRIDE}th data line thereafter`;

const output = resolveOutput("test/bidi/conformance-smoke.json", process.argv[3]);
const { text, sha256, url } = readVerified("BidiCharacterTest.txt", process.argv[2]);

const DIRECTIONS = { 0: "ltr", 1: "rtl", 2: "auto" };
const cases = [];
let dataLine = 0;

for (const [index, raw] of text.split(/\r?\n/).entries()) {
  const line = raw.trim();
  if (!line || line.startsWith("#")) continue;
  const fields = line.split(";").map((field) => field.trim());
  if (fields.length !== 5) continue;
  dataLine++;
  if (dataLine > HEAD && dataLine % STRIDE !== 0) continue;
  const direction = DIRECTIONS[fields[1]];
  if (direction === undefined) throw new Error(`line ${index + 1}: unknown paragraph direction ${fields[1]}`);
  cases.push({
    sourceLine: index + 1,
    codePoints: fields[0],
    direction,
    paragraphLevel: Number(fields[2]),
    // "x" marks a character X9 removed, which has no resolved level.
    levels: fields[3].split(/\s+/).filter(Boolean).map((value) => (value === "x" ? null : Number(value))),
    order: fields[4].split(/\s+/).filter(Boolean).map(Number),
  });
}

const fixture = {
  comment: "Generated by scripts/select-smoke-cases.mjs. Do not edit by hand.",
  source: {
    file: "BidiCharacterTest.txt",
    unicodeVersion: manifest.unicodeVersion,
    url,
    sha256,
    selection: SELECTION,
  },
  cases,
};

fs.writeFileSync(output, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`generated ${output}: ${cases.length} cases from ${dataLine} data lines`);
